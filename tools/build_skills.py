#!/usr/bin/env python3
"""Generate the Kiro skills from the shared skills.

Sources (edit these; Claude Code and Antigravity load them as they are):
  skills/handoff/SKILL.md   save          /handoff:handoff
  skills/resume/SKILL.md    resume        /handoff:resume
  skills/list/SKILL.md      list          /handoff:list

Generated (do not edit by hand):
  kiro/skills/handoff/, kiro/skills/handoff-resume/, kiro/skills/handoff-list/
      Kiro skills are not namespaced by plugin, so they carry the prefix in
      their names, and Kiro's IDE does not fill in $ARGUMENTS.

  python3 tools/build_skills.py          write the files
  python3 tools/build_skills.py --check  exit 1 if a generated file is out of date
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = "<!-- Generated by tools/build_skills.py from {src}. Edit the source, then run the script. -->\n"
KIRO_NAMES = {"handoff": "handoff", "resume": "handoff-resume", "list": "handoff-list"}


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        return f.read()


def split_frontmatter(text):
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    return (m.group(1), text[m.end():]) if m else ("", text)


def for_kiro(body):
    body = body.replace("/handoff:resume", "/handoff-resume").replace("/handoff:list", "/handoff-list")
    body = re.sub(
        r"^Argument \(whatever the user typed after the command, may be empty\): \$ARGUMENTS$",
        "Argument: whatever the user typed after the command or asked for (may be empty).",
        body,
        flags=re.M,
    )
    return body


def kiro_skill(source_name):
    src = f"skills/{source_name}/SKILL.md"
    meta, body = split_frontmatter(read(src))
    description = re.search(r"^description: (.*)$", meta, re.M).group(1)
    name = KIRO_NAMES[source_name]
    return f"---\nname: {name}\ndescription: {description}\n---\n" + HEADER.format(src=src) + for_kiro(body)


def outputs():
    return {f"kiro/skills/{KIRO_NAMES[n]}/SKILL.md": kiro_skill(n) for n in KIRO_NAMES}


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for rel, content in outputs().items():
        path = os.path.join(ROOT, *rel.split("/"))
        try:
            with open(path, encoding="utf-8") as f:
                current = f.read()
        except OSError:
            current = None
        if current == content:
            continue
        if check:
            stale.append(rel)
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        print("wrote", rel)
    if stale:
        print("Out of date (run python3 tools/build_skills.py):\n  " + "\n  ".join(stale))
        sys.exit(1)


if __name__ == "__main__":
    main()
